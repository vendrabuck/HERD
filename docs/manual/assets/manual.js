/* HERD manual, interactions: nav active state, copy buttons,
   back-to-top, mobile nav, smooth anchor offset, and search (issue #1298).

   Search reads the prebuilt index that assets/search-index.js assigns to
   window.HERD_MANUAL_SEARCH_INDEX (generated by
   scripts/build_manual_search_index.py). No page loads that file: the first
   focus of, or keystroke in, the search box adds a script element for it
   (which also works from file://), and a query typed before it arrives is
   answered when it does.
   HERDManualSearch below is the pure matching and ranking part: no DOM, so
   Node can load this file (module.exports) and test it directly. The browser
   part builds every result from text nodes and createElement, never from
   markup, so page text cannot inject anything through a result.

   Matching and ranking (HERDManualSearch.search):
   - The query is split into terms, lower-cased: a dotted version such as
     0.7.0 (digits joined by single dots) is one term, and otherwise a term is
     a run of letters and digits. Page text is split the same way. Every term
     is required. A term matches a word that equals it, except the
     LAST term, which matches any word it is a prefix of (search as you type).
   - A term may be found in the section heading (its heading and eyebrow), its
     body text, or its page title. A section matches when every term is found
     in at least one of them.
   - Matches sort by, in order: (1) when the query holds a version term,
     sections whose page title contains it exactly, then sections whose
     heading does, then the rest (so "0.3.0" leads with the 0.3.0 release
     page); (2) current pages, the current release page included, before
     earlier release pages; (3) more terms found in the heading first; (4)
     headings made only of query words first; (5) more body words matched
     first; (6) index order, which is page file name, then position on the
     page. The page title can satisfy a term but never counts as a heading
     hit. Every key is a number, so the order is total and
     the same on every run. */
var HERDManualSearch = (function () {
  // A letter run directly before a version is its own word ("v0.7.0" gives
  // "v" and "0.7.0"); then a version; then any other letter and digit run.
  var WORD = /\p{L}+(?=\d+(?:\.\d+)+)|\d+(?:\.\d+)+|[\p{L}\p{N}]+/gu;
  var VERSION = /^\d+(?:\.\d+)+$/;
  var SNIPPET_BEFORE = 60;
  var SNIPPET_LENGTH = 200;
  var ELLIPSIS = "\u2026";

  // Word spans of a text: [{start, end, word}], word lower-cased.
  function spans(text) {
    var out = [], m;
    WORD.lastIndex = 0;
    while ((m = WORD.exec(text)) !== null) {
      out.push({ start: m.index, end: m.index + m[0].length, word: m[0].toLowerCase() });
    }
    return out;
  }

  // Query terms: [{term, prefix}]. Duplicates merge; the last term is a prefix.
  function parseQuery(query) {
    var words = spans(String(query || "")).map(function (s) { return s.word; });
    var terms = [], seen = {};
    words.forEach(function (word, i) {
      var prefix = i === words.length - 1;
      if (Object.prototype.hasOwnProperty.call(seen, word)) {
        terms[seen[word]].prefix = terms[seen[word]].prefix || prefix;
      } else {
        seen[word] = terms.length;
        terms.push({ term: word, prefix: prefix });
      }
    });
    return terms;
  }

  function termMatches(t, word) {
    return t.prefix ? word.indexOf(t.term) === 0 : word === t.term;
  }

  function anyTerm(terms, word) {
    for (var i = 0; i < terms.length; i++) if (termMatches(terms[i], word)) return true;
    return false;
  }

  function hasTerm(t, wordSpans) {
    for (var i = 0; i < wordSpans.length; i++) if (termMatches(t, wordSpans[i].word)) return true;
    return false;
  }

  // Split text into [{text, mark}] parts, marking every word a term matches.
  function markParts(text, wordSpans, terms) {
    var parts = [], at = 0;
    wordSpans.forEach(function (s) {
      if (!anyTerm(terms, s.word)) return;
      if (s.start > at) parts.push({ text: text.slice(at, s.start), mark: false });
      parts.push({ text: text.slice(s.start, s.end), mark: true });
      at = s.end;
    });
    if (at < text.length) parts.push({ text: text.slice(at), mark: false });
    return parts;
  }

  // Never cut between the two halves of a surrogate pair.
  function whole(text, i) {
    var c = text.charCodeAt(i);
    var b = text.charCodeAt(i - 1);
    return i > 0 && i < text.length && c >= 0xdc00 && c <= 0xdfff && b >= 0xd800 && b <= 0xdbff
      ? i - 1 : i;
  }

  // A window of the body around its first matched word, cut at spaces.
  function snippet(text, wordSpans, terms) {
    var first = null;
    for (var i = 0; i < wordSpans.length; i++) {
      if (anyTerm(terms, wordSpans[i].word)) { first = wordSpans[i]; break; }
    }
    var start = first ? Math.max(0, first.start - SNIPPET_BEFORE) : 0;
    if (start > 0) {
      var space = text.indexOf(" ", start);
      start = space >= 0 && (!first || space < first.start) ? space + 1 : start;
    }
    var end = Math.min(text.length, start + SNIPPET_LENGTH);
    if (end < text.length) {
      var back = text.lastIndexOf(" ", end);
      if (back > start && (!first || back >= first.end)) end = back;
    }
    start = whole(text, start);
    end = whole(text, end);
    var cut = text.slice(start, end);
    var inner = spans(cut);
    var parts = markParts(cut, inner, terms);
    if (start > 0) parts.unshift({ text: ELLIPSIS, mark: false });
    if (end < text.length) parts.push({ text: ELLIPSIS, mark: false });
    return parts;
  }

  // Precompute word spans once per index object.
  function prepare(index) {
    var pages = (index && index.pages) || [];
    var sections = (index && index.sections) || [];
    return sections.map(function (s, position) {
      var page = pages[s.page] || { file: "", title: "", kind: "page" };
      var headingText = s.eyebrow ? s.heading + " " + s.eyebrow : s.heading;
      return {
        position: position,
        section: s,
        page: page,
        headingSpans: spans(headingText),
        ownHeadingSpans: spans(s.heading),
        bodySpans: spans(s.text || ""),
        titleSpans: spans(page.title || ""),
      };
    });
  }

  function search(index, query, limit) {
    var prepared = index && index.__prepared ? index.__prepared : prepare(index);
    var terms = parseQuery(query);
    if (!terms.length) return { terms: terms, total: 0, results: [] };
    var versions = terms.filter(function (t) { return VERSION.test(t.term); });
    function hasVersion(wordSpans) {
      return versions.some(function (t) {
        return wordSpans.some(function (s) { return s.word === t.term; });
      });
    }
    var hits = [];
    prepared.forEach(function (p) {
      var headingHits = 0;
      for (var i = 0; i < terms.length; i++) {
        var inHeading = hasTerm(terms[i], p.headingSpans);
        if (inHeading) headingHits++;
        else if (!hasTerm(terms[i], p.bodySpans) && !hasTerm(terms[i], p.titleSpans)) return;
      }
      var bodyCount = 0;
      p.bodySpans.forEach(function (s) { if (anyTerm(terms, s.word)) bodyCount++; });
      var exact = p.ownHeadingSpans.length > 0 && p.ownHeadingSpans.every(function (s) {
        return anyTerm(terms, s.word);
      });
      var versionRank = !versions.length ? 0
        : hasVersion(p.titleSpans) ? 0 : hasVersion(p.headingSpans) ? 1 : 2;
      hits.push({
        p: p,
        keys: [
          versionRank,
          p.page.kind === "earlier-release" ? 1 : 0,
          -headingHits,
          exact ? 0 : 1,
          -bodyCount,
          p.position,
        ],
      });
    });
    hits.sort(function (a, b) {
      for (var i = 0; i < a.keys.length; i++) {
        if (a.keys[i] !== b.keys[i]) return a.keys[i] - b.keys[i];
      }
      return 0;
    });
    var shown = typeof limit === "number" ? hits.slice(0, limit) : hits;
    return {
      terms: terms,
      total: hits.length,
      results: shown.map(function (h) {
        var s = h.p.section, page = h.p.page;
        return {
          file: page.file,
          title: page.title,
          kind: page.kind,
          release: page.kind === "release" || page.kind === "earlier-release",
          anchor: s.anchor,
          href: s.anchor ? page.file + "#" + s.anchor : page.file,
          heading: s.heading,
          eyebrow: s.eyebrow,
          headingParts: markParts(s.heading, h.p.ownHeadingSpans, terms),
          snippetParts: snippet(s.text || "", h.p.bodySpans, terms),
        };
      }),
    };
  }

  return { parseQuery: parseQuery, prepare: prepare, search: search };
})();

if (typeof module !== "undefined" && module.exports) module.exports = HERDManualSearch;

(function () {
  // Under Node (the functional tests) only the pure part above is wanted.
  if (typeof module !== "undefined" && module.exports) return;

  // ----- copy buttons on .cmd blocks -----
  document.querySelectorAll(".cmd").forEach(function (block) {
    var btn = document.createElement("button");
    btn.className = "copy";
    btn.type = "button";
    btn.textContent = "Copy";
    btn.addEventListener("click", function () {
      var code = block.querySelector("code");
      var text = code ? code.innerText : block.innerText;
      navigator.clipboard && navigator.clipboard.writeText(text).then(function () {
        btn.textContent = "Copied";
        btn.classList.add("done");
        setTimeout(function () { btn.textContent = "Copy"; btn.classList.remove("done"); }, 1600);
      });
    });
    block.appendChild(btn);
  });

  // ----- back to top -----
  var totop = document.getElementById("totop");
  if (totop) {
    window.addEventListener("scroll", function () {
      totop.classList.toggle("show", window.scrollY > 520);
    }, { passive: true });
    totop.addEventListener("click", function () {
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
  }

  // ----- mobile nav toggle -----
  var tgl = document.querySelector(".navtoggle");
  var nav = document.querySelector(".manualbar nav");
  if (tgl && nav) tgl.addEventListener("click", function () { nav.classList.toggle("open"); });

  // ----- sidebar scrollspy -----
  var links = Array.prototype.slice.call(document.querySelectorAll(".side a[href^='#']"));
  if (links.length) {
    var targets = links.map(function (a) {
      var el = document.getElementById(a.getAttribute("href").slice(1));
      return el ? { a: a, el: el } : null;
    }).filter(Boolean);
    var spy = function () {
      var y = window.scrollY + 110, cur = targets[0];
      targets.forEach(function (t) { if (t.el.offsetTop <= y) cur = t; });
      links.forEach(function (a) { a.classList.remove("active"); });
      if (cur) cur.a.classList.add("active");
    };
    window.addEventListener("scroll", spy, { passive: true });
    spy();
  }

  // ----- search -----
  // The index sits beside this file, wherever the page loaded it from.
  var self = document.currentScript;
  var indexUrl = self && self.src
    ? self.src.replace(/manual\.js(?:[?#].*)?$/, "search-index.js")
    : "assets/search-index.js";
  var bar = document.querySelector(".manualbar");
  if (bar) initSearch(bar, indexUrl);
})();

function initSearch(bar, indexUrl) {
  var LIMIT = 20;

  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }

  function appendParts(parent, parts) {
    parts.forEach(function (part) {
      if (part.mark) parent.appendChild(el("mark", "", part.text));
      else parent.appendChild(document.createTextNode(part.text));
    });
  }

  var box = el("div", "msearch");
  box.setAttribute("role", "search");
  var label = el("label", "msearch-sr", "Search the manual");
  label.htmlFor = "msearch-input";
  var input = el("input", "msearch-input");
  input.id = "msearch-input";
  input.type = "search";
  input.placeholder = "Search";
  input.autocomplete = "off";
  input.spellcheck = false;
  input.setAttribute("role", "combobox");
  input.setAttribute("aria-autocomplete", "list");
  input.setAttribute("aria-expanded", "false");
  input.setAttribute("aria-controls", "msearch-results");
  input.setAttribute("aria-keyshortcuts", "/");
  var hint = el("kbd", "msearch-key", "/");
  hint.setAttribute("aria-hidden", "true");
  hint.title = "Press / to search";
  // The live region exists, empty, from the start and outside the panel, so
  // its first change is announced; the panel's visible count line repeats
  // the same words and is hidden from assistive technology.
  var status = el("p", "msearch-sr");
  status.id = "msearch-status";
  status.setAttribute("role", "status");
  status.setAttribute("aria-live", "polite");
  var panel = el("div", "msearch-panel");
  panel.hidden = true;
  var count = el("p", "msearch-count");
  count.setAttribute("aria-hidden", "true");
  var list = el("div", "msearch-results");
  list.id = "msearch-results";
  list.setAttribute("role", "listbox");
  list.setAttribute("aria-label", "Search results");
  panel.appendChild(count);
  panel.appendChild(list);
  box.appendChild(label);
  box.appendChild(input);
  box.appendChild(hint);
  box.appendChild(status);
  box.appendChild(panel);
  bar.appendChild(box);
  // Clicks inside the panel keep focus in the input, so the panel stays open
  // while its list is scrolled; a click on a result still follows its link.
  panel.addEventListener("mousedown", function (e) { e.preventDefault(); });
  var nav = bar.querySelector("nav");

  var options = [];
  var active = -1;
  var preparedFor = null;
  var loading = "idle"; // idle, loading, done, failed

  function setStatus(text, empty) {
    status.textContent = text;
    count.textContent = text;
    count.className = empty ? "msearch-count empty" : "msearch-count";
  }

  // Add the index's script element once, on the first use of the box.
  function ensureIndex() {
    if (loading !== "idle" || window.HERD_MANUAL_SEARCH_INDEX) return;
    loading = "loading";
    var script = document.createElement("script");
    script.src = indexUrl;
    script.async = true;
    script.addEventListener("load", function () {
      loading = window.HERD_MANUAL_SEARCH_INDEX ? "done" : "failed";
      if (document.activeElement === input) render();
    });
    script.addEventListener("error", function () {
      loading = "failed";
      if (document.activeElement === input) render();
    });
    (document.head || document.body).appendChild(script);
  }

  function index() {
    var idx = window.HERD_MANUAL_SEARCH_INDEX;
    if (!idx || !idx.sections) return null;
    if (preparedFor !== idx) {
      Object.defineProperty(idx, "__prepared", {
        value: HERDManualSearch.prepare(idx), configurable: true, enumerable: false,
      });
      preparedFor = idx;
    }
    return idx;
  }

  function setOpen(open) {
    panel.hidden = !open;
    input.setAttribute("aria-expanded", open ? "true" : "false");
    if (!open) setActive(-1);
  }

  function setActive(i) {
    if (active >= 0 && options[active]) options[active].setAttribute("aria-selected", "false");
    active = i;
    if (active >= 0 && options[active]) {
      options[active].setAttribute("aria-selected", "true");
      input.setAttribute("aria-activedescendant", options[active].id);
      if (options[active].scrollIntoView) options[active].scrollIntoView({ block: "nearest" });
    } else {
      input.removeAttribute("aria-activedescendant");
    }
  }

  function render() {
    var query = input.value;
    list.textContent = "";
    options = [];
    active = -1;
    input.removeAttribute("aria-activedescendant");
    if (!query.trim()) { setStatus("", false); setOpen(false); return; }
    var idx = index();
    if (!idx) {
      setStatus(loading === "failed" || loading === "done"
        ? "The search index did not load." : "Loading the search index\u2026", true);
      setOpen(true);
      return;
    }
    var found = HERDManualSearch.search(idx, query, LIMIT);
    if (!found.terms.length) { setStatus("", false); setOpen(false); return; }
    if (!found.total) {
      setStatus("No results for \u201c" + query.trim() + "\u201d.", true);
    } else {
      setStatus(found.total > found.results.length
        ? "Top " + found.results.length + " of " + found.total + " results"
        : found.total + (found.total === 1 ? " result" : " results"), false);
    }
    found.results.forEach(function (r, i) {
      var a = el("a", "msearch-option");
      a.id = "msearch-opt-" + i;
      a.href = r.href;
      a.tabIndex = -1;
      a.setAttribute("role", "option");
      a.setAttribute("aria-selected", "false");
      var meta = el("span", "msearch-meta");
      meta.appendChild(el("span", "msearch-page", r.title));
      if (r.release) meta.appendChild(el("span", "msearch-tag", "Release notes"));
      var head = el("span", "msearch-heading");
      appendParts(head, r.headingParts);
      var snip = el("span", "msearch-snippet");
      appendParts(snip, r.snippetParts);
      a.appendChild(meta);
      a.appendChild(head);
      a.appendChild(snip);
      a.addEventListener("mousemove", function () { if (active !== i) setActive(i); });
      a.addEventListener("click", function () { setOpen(false); });
      list.appendChild(a);
      options.push(a);
    });
    setOpen(true);
  }

  function go(i) {
    var target = options[i];
    if (!target) return;
    setOpen(false);
    window.location.href = target.href;
  }

  input.addEventListener("input", function () { ensureIndex(); render(); });
  input.addEventListener("focus", function () {
    ensureIndex();
    if (nav) nav.classList.remove("open");
    if (input.value.trim()) render();
  });
  input.addEventListener("keydown", function (e) {
    ensureIndex();
    if (e.key === "ArrowDown") {
      e.preventDefault();
      if (panel.hidden) render();
      if (options.length) setActive(active < options.length - 1 ? active + 1 : 0);
    } else if (e.key === "ArrowUp") {
      e.preventDefault();
      if (options.length) setActive(active > 0 ? active - 1 : options.length - 1);
    } else if (e.key === "Enter") {
      if (!panel.hidden && options.length) {
        e.preventDefault();
        go(active >= 0 ? active : 0);
      }
    } else if (e.key === "Escape") {
      e.preventDefault();
      if (!panel.hidden) setOpen(false);
      else if (input.value) input.value = "";
      else input.blur();
    }
  });
  document.addEventListener("mousedown", function (e) {
    if (box.isConnected && !box.contains(e.target)) setOpen(false);
  });
  box.addEventListener("focusout", function (e) {
    if (!e.relatedTarget || !box.contains(e.relatedTarget)) setOpen(false);
  });
  document.addEventListener("keydown", function (e) {
    if (!box.isConnected) return;
    if (e.key !== "/" || e.ctrlKey || e.metaKey || e.altKey || e.defaultPrevented) return;
    var t = e.target;
    var tag = t && t.tagName ? t.tagName.toLowerCase() : "";
    if (tag === "input" || tag === "textarea" || tag === "select" || (t && t.isContentEditable)) return;
    e.preventDefault();
    input.focus();
    input.select();
  });
}
